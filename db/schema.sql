-- Pulse schema. Idempotent: safe to run repeatedly (scripts/seed.ts applies it before seeding).

CREATE TABLE IF NOT EXISTS products (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                text          NOT NULL CHECK (char_length(name) BETWEEN 1 AND 200),
  sku                 text          NOT NULL UNIQUE CHECK (char_length(sku) BETWEEN 1 AND 64),
  price               numeric(10,2) NOT NULL CHECK (price >= 0),
  stock               integer       NOT NULL DEFAULT 0 CHECK (stock >= 0),
  low_stock_threshold integer       NOT NULL DEFAULT 10 CHECK (low_stock_threshold >= 0),
  image_url           text          CHECK (image_url IS NULL OR char_length(image_url) <= 2048),
  created_at          timestamptz   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orders (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name text          NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 200),
  status        text          NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  total         numeric(10,2) NOT NULL CHECK (total >= 0),
  created_at    timestamptz   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS order_items (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   integer       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id integer       NOT NULL REFERENCES products (id),
  quantity   integer       NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0)
);

-- Live feed, KPIs "today", revenue (last 24h) and heatmap (last 7 days) all filter/sort by time.
CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders (created_at DESC);
-- Status filter in the orders table and the "pending orders" KPI.
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);
-- Item counts per order (feed + table) and FK lookups.
CREATE INDEX IF NOT EXISTS order_items_order_id_idx ON order_items (order_id);
CREATE INDEX IF NOT EXISTS order_items_product_id_idx ON order_items (product_id);
-- Low-stock alerts: a tiny partial index containing only the products that need attention.
CREATE INDEX IF NOT EXISTS products_low_stock_idx ON products (id) WHERE stock <= low_stock_threshold;
